#!/usr/bin/env python3
"""Turn pinned GitHub repositories into license-checked byte-corpus chunks.

This is the supply side of NaNLM's continuous training loop. It never trains
and never talks to the model runtime. Its only output is:

    chunks/...txt       normalized UTF-8 byte chunks
    manifest.jsonl      one record per chunk, with provenance and hashes
    report.json         counts, languages, licenses, skip reasons
    manifest.sha256     hash of manifest.jsonl

The runner ring consumes manifest.jsonl. Each job can concatenate its assigned
chunks, build a normal additive shard with nanlm_shard, and upload the shard.

Design rules:
  * pin a commit (never train the moving default branch silently);
  * default to a permissive-license allowlist;
  * reject secrets, binaries, minified files, generated files, vendored trees;
  * normalize only line endings and BOM, never reformat code;
  * deterministic ordering and hashes;
  * no network at inference, no network unless --github is used.
"""

