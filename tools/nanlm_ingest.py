@dataclass
class RepoSource:
    root: Path
    repo: str
    commit: str
    source: str
    license: str
    tempdir: tempfile.TemporaryDirectory | None = None


@dataclass
class Stats:
    files_seen: int = 0
    files_kept: int = 0
    chunks: int = 0
    bytes_kept: int = 0
    skipped: dict[str, int] = field(default_factory=dict)
    languages: dict[str, int] = field(default_factory=dict)
    licenses: dict[str, int] = field(default_factory=dict)

    def skip(self, reason: str) -> None:
        self.skipped[reason] = self.skipped.get(reason, 0) + 1


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_text(text: str) -> str:
    return sha256_bytes(text.encode("utf-8"))


def detect_license(text: str) -> str | None:
    for spdx in SPDX_RE.findall(text):
        if spdx:
            return spdx
    low = text.lower()
    if "apache license" in low and "version 2.0" in low:
        return "Apache-2.0"
    if "mit license" in low or "permission is hereby granted, free of charge" in low:
        return "MIT"
    if "redistribution and use in source and binary forms" in low:
        if "neither the name" in low or "third clause" in low:
            return "BSD-3-Clause"
        return "BSD-2-Clause"
    if "isc license" in low or "permission to use, copy, modify, and/or distribute" in low:
        return "ISC"
    if "mozilla public license" in low and "2.0" in low:
        return "MPL-2.0"
    if "gnu affero general public license" in low:
        return "AGPL-3.0"
    if "gnu general public license" in low:
        if "version 3" in low:
            return "GPL-3.0"
        if "version 2" in low:
            return "GPL-2.0"
    if "gnu lesser general public license" in low:
        return "LGPL-3.0" if "version 3" in low else "LGPL-2.1"
    if "this is free and unencumbered software released into the public domain" in low:
        return "Unlicense"
    if "cc0 1.0 universal" in low or "creative commons zero" in low:
        return "CC0-1.0"
    return None


def find_license(root: Path) -> str | None:
    candidates = sorted(
        p for p in root.iterdir()
        if p.is_file() and p.name.lower().startswith(("license", "copying", "licence"))
    )
    for path in candidates:
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        lic = detect_license(text)
        if lic:
            return lic
    return None


def file_license(text: str, fallback: str) -> str:
    match = SPDX_RE.search(text[:4096])
    return match.group(1) if match else fallback


def language_for(path: Path) -> str:
    return EXT_LANGUAGE.get(path.suffix, "Text")


def looks_minified(name: str, text: str) -> bool:
    low = name.lower()
    if ".min." in low or low.endswith(".map"):
        return True
    lines = text.splitlines()
    if not lines:
        return False
    longest = max(len(line) for line in lines)
    avg = sum(len(line) for line in lines) / len(lines)
    return longest > 4000 or (avg > 300 and len(lines) > 4)


def looks_generated(text: str) -> bool:
    head = text[:2048].lower()
    return any(marker in head for marker in GENERATED_MARKERS)


def contains_secret(text: str) -> bool:
    return any(pattern.search(text) for pattern in SECRET_PATTERNS)


def normalize_text(raw: bytes) -> str | None:
    if b"\x00" in raw:
        return None
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return None
    if text.startswith("\ufeff"):
        text = text[1:]
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if not text.strip():
        return None
    if not text.endswith("\n"):
        text += "\n"
    return text


def iter_files(root: Path) -> Iterable[Path]:
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(
            d for d in dirnames if d.lower() not in SKIP_DIRS and not d.startswith(".")
        )
        for name in sorted(filenames):
            if name.startswith("."):
                continue
            yield Path(dirpath) / name


def split_chunks(text: str, max_bytes: int) -> list[tuple[int, int, str]]:
    """Split on newline boundaries; offsets are character offsets in text."""
    data = text.encode("utf-8")
    if len(data) <= max_bytes:
        return [(0, len(data), text)]
    chunks: list[tuple[int, int, str]] = []
    start = 0
    while start < len(data):
        end = min(start + max_bytes, len(data))
        if end < len(data):
            cut = data.rfind(b"\n", start, end)
            if cut > start + max_bytes // 2:
                end = cut + 1
        piece = data[start:end].decode("utf-8", errors="strict")
        chunks.append((start, end, piece))
        start = end
    return chunks


def safe_component(value: str, limit: int = 48) -> str:
    value = re.sub(r"[^A-Za-z0-9._-]+", "_", value).strip("._")
    return (value or "x")[:limit]


def fetch_github(spec: str, token: str | None) -> RepoSource:
    if "@" in spec:
        repo, ref = spec.rsplit("@", 1)
    else:
        repo, ref = spec, "HEAD"
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "NaNLM-ingest"}
    if token:
        headers["Authorization"] = f"Bearer {token}"

    commit = ref
    try:
        req = urllib.request.Request(
            f"https://api.github.com/repos/{repo}/commits/{ref}", headers=headers
        )
        with urllib.request.urlopen(req, timeout=30) as response:
            payload = json.load(response)
            commit = payload.get("sha", ref)
    except (urllib.error.URLError, urllib.error.HTTPError, ValueError):
        pass

    url = f"https://api.github.com/repos/{repo}/tarball/{commit}"
    req = urllib.request.Request(url, headers=headers)
    tmp = tempfile.TemporaryDirectory(prefix="nanlm-gh-")
    archive = Path(tmp.name) / "repo.tar.gz"
    try:
        with urllib.request.urlopen(req, timeout=120) as response, open(archive, "wb") as out:
            total = 0
            while True:
                block = response.read(1024 * 1024)
                if not block:
                    break
                total += len(block)
                if total > MAX_ARCHIVE_BYTES:
                    raise RuntimeError(f"archive too large for {repo}")
                out.write(block)
        extract_root = Path(tmp.name) / "src"
        extract_root.mkdir()
        with tarfile.open(archive, "r:gz") as tar:
            members = []
            for member in tar.getmembers():
                target = (extract_root / member.name).resolve()
                if not str(target).startswith(str(extract_root.resolve()) + os.sep):
                    continue
                members.append(member)
            tar.extractall(extract_root, members=members)
        children = [p for p in extract_root.iterdir() if p.is_dir()]
        root = children[0] if len(children) == 1 else extract_root
        license_id = find_license(root) or "NOASSERTION"
        return RepoSource(
            root=root,
            repo=repo,
            commit=commit,
            source=f"https://github.com/{repo}/tree/{commit}",
            license=license_id,
            tempdir=tmp,
        )
    except Exception:
        tmp.cleanup()
        raise


def ingest_repo(
    source: RepoSource,
    out_dir: Path,
    stats: Stats,
    chunk_bytes: int,
    max_file_bytes: int,
    max_files: int,
    max_bytes: int,
    allow_unknown: bool,
    allow_copyleft: bool,
    include_docs: bool,
    manifest: list[dict],
) -> None:
    license_id = source.license
    if license_id == "NOASSERTION" and not allow_unknown:
        stats.skip("unknown-license-repo")
        return
    if license_id in COPYLEFT_LICENSES and not allow_copyleft:
        stats.skip("copyleft-license-repo")
        return

    slug_repo = safe_component(source.repo.replace("/", "__"), 60)
    chunk_root = out_dir / "chunks" / slug_repo
    kept_files = 0

    for path in iter_files(source.root):
        if stats.files_seen >= max_files or stats.bytes_kept >= max_bytes:
            stats.skip("budget-exhausted")
            break
        stats.files_seen += 1
        rel = path.relative_to(source.root).as_posix()
        name = path.name
        ext = path.suffix

        if name in SKIP_FILES:
            stats.skip("lockfile")
            continue
        if ext not in EXT_LANGUAGE:
            stats.skip("extension")
            continue
        if ext in DOC_EXTS and not include_docs:
            stats.skip("docs-disabled")
            continue
        try:
            size = path.stat().st_size
        except OSError:
            stats.skip("stat-error")
            continue
        if size > max_file_bytes:
            stats.skip("too-large")
            continue
        try:
            raw = path.read_bytes()
        except OSError:
            stats.skip("read-error")
            continue
        text = normalize_text(raw)
        if text is None:
            stats.skip("binary-or-nonutf8")
            continue
        if looks_minified(name, text):
            stats.skip("minified")
            continue
        if looks_generated(text):
            stats.skip("generated")
            continue
        if contains_secret(text):
            stats.skip("secret")
            continue

        file_license_id = file_license(text, license_id)
        if file_license_id == "NOASSERTION" and not allow_unknown:
            stats.skip("unknown-license-file")
            continue
        if file_license_id in COPYLEFT_LICENSES and not allow_copyleft:
            stats.skip("copyleft-license-file")
            continue

        lang = language_for(path)
        stats.files_kept += 1
        stats.languages[lang] = stats.languages.get(lang, 0) + 1
        stats.licenses[file_license_id] = stats.licenses.get(file_license_id, 0) + 1
        kept_files += 1

        file_hash = sha256_text(text)
        chunks = split_chunks(text, chunk_bytes)
        slug_path = safe_component(rel.replace("/", "__"), 80)
        for index, (start, end, piece) in enumerate(chunks):
            chunk_hash = sha256_text(piece)
            chunk_name = f"{file_hash[:12]}-{index:04d}.txt"
            chunk_path = chunk_root / slug_path / chunk_name
            chunk_path.parent.mkdir(parents=True, exist_ok=True)
            chunk_path.write_text(piece, encoding="utf-8")
            record = {
                "type": "chunk",
                "schema": SCHEMA,
                "repo": source.repo,
                "commit": source.commit,
                "source": source.source,
                "path": rel,
                "language": lang,
                "license": file_license_id,
                "file_sha256": file_hash,
                "chunk_index": index,
                "chunks": len(chunks),
                "start": start,
                "end": end,
                "bytes": len(piece.encode("utf-8")),
                "chunk_sha256": chunk_hash,
                "text": chunk_path.relative_to(out_dir).as_posix(),
                "url": f"https://github.com/{source.repo}/blob/{source.commit}/{rel}",
            }
            manifest.append(record)
            stats.chunks += 1
            stats.bytes_kept += record["bytes"]


def write_outputs(
    out_dir: Path,
    manifest: list[dict],
    stats: Stats,
    concat: Path | None,
) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = out_dir / "manifest.jsonl"
    with open(manifest_path, "w", encoding="utf-8", newline="\n") as f:
        for record in manifest:
            f.write(json.dumps(record, sort_keys=True, separators=(",", ":")) + "\n")
    digest = sha256_bytes(manifest_path.read_bytes())
    (out_dir / "manifest.sha256").write_text(digest + "\n", encoding="utf-8")

    report = {
        "schema": SCHEMA,
        "files_seen": stats.files_seen,
        "files_kept": stats.files_kept,
        "chunks": stats.chunks,
        "bytes_kept": stats.bytes_kept,
        "skipped": dict(sorted(stats.skipped.items())),
        "languages": dict(sorted(stats.languages.items())),
        "licenses": dict(sorted(stats.licenses.items())),
        "manifest_sha256": digest,
    }
    (out_dir / "report.json").write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    if concat is not None:
        concat.parent.mkdir(parents=True, exist_ok=True)
        with open(concat, "w", encoding="utf-8", newline="\n") as f:
            for record in manifest:
                f.write((out_dir / record["text"]).read_text(encoding="utf-8"))
                if not record["text"].endswith("\n"):
                    f.write("\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", action="append", default=[], metavar="DIR",
                        help="local repository directory (repeatable)")
    parser.add_argument("--github", action="append", default=[], metavar="OWNER/REPO[@REF]",
                        help="download a pinned GitHub tarball (repeatable)")
    parser.add_argument("--out", required=True, metavar="DIR")
    parser.add_argument("--concat", metavar="FILE", help="also write all chunks in order")
    parser.add_argument("--allow-unknown-license", action="store_true")
    parser.add_argument("--allow-copyleft", action="store_true")
    parser.add_argument("--include-docs", action="store_true")
    parser.add_argument("--max-file-bytes", type=int, default=1024 * 1024)
    parser.add_argument("--max-files", type=int, default=200_000)
    parser.add_argument("--max-bytes", type=int, default=2 * 1024 * 1024 * 1024)
    parser.add_argument("--chunk-bytes", type=int, default=64 * 1024)
    args = parser.parse_args()

    if not args.repo and not args.github:
        parser.error("give at least one --repo or --github source")
    if args.chunk_bytes < 256:
        parser.error("--chunk-bytes must be at least 256")

    out_dir = Path(args.out)
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    sources: list[RepoSource] = []
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    try:
        for directory in args.repo:
            root = Path(directory).resolve()
            if not root.is_dir():
                print(f"ingest: not a directory: {root}", file=sys.stderr)
                return 1
            try:
                commit = subprocess.check_output(
                    ["git", "-C", str(root), "rev-parse", "HEAD"],
                    text=True, stderr=subprocess.DEVNULL,
                ).strip()
                origin = subprocess.check_output(
                    ["git", "-C", str(root), "remote", "get-url", "origin"],
                    text=True, stderr=subprocess.DEVNULL,
                ).strip()
            except (subprocess.CalledProcessError, FileNotFoundError):
                commit = "local"
                origin = str(root)
            repo = origin.rstrip("/").split("/")[-1]
            if repo.endswith(".git"):
                repo = repo[:-4]
            license_id = find_license(root) or "NOASSERTION"
            sources.append(RepoSource(root=root, repo=repo, commit=commit,
                                      source=str(root), license=license_id))
        for spec in args.github:
            sources.append(fetch_github(spec, token))

        stats = Stats()
        manifest: list[dict] = []
        for source in sources:
            ingest_repo(
                source=source,
                out_dir=out_dir,
                stats=stats,
                chunk_bytes=args.chunk_bytes,
                max_file_bytes=args.max_file_bytes,
                max_files=args.max_files,
                max_bytes=args.max_bytes,
                allow_unknown=args.allow_unknown_license,
                allow_copyleft=args.allow_copyleft,
                include_docs=args.include_docs,
                manifest=manifest,
            )
        manifest.sort(key=lambda r: (r["repo"], r["path"], r["chunk_index"]))
        concat_path = Path(args.concat) if args.concat else None
        write_outputs(out_dir, manifest, stats, concat_path)
        print(
            f"ingest: files={stats.files_kept} chunks={stats.chunks} "
            f"bytes={stats.bytes_kept} skipped={sum(stats.skipped.values())} "
            f"manifest={sha256_bytes((out_dir / 'manifest.jsonl').read_bytes())}"
        )
        if stats.chunks == 0:
            print("ingest: no chunks kept", file=sys.stderr)
            return 1
        return 0
    finally:
        for source in sources:
            if source.tempdir is not None:
                source.tempdir.cleanup()


if __name__ == "__main__":
    raise SystemExit(main())
