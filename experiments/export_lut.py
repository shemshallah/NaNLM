#!/usr/bin/env python3
"""Compile a learned 3-gate LUT tree (fixed or routed) to NaN16 .nas.

The emitted program loops over all 256 8-bit inputs, extracts x0..x3, runs the
gate tree, and prints one bit per line. The expected file is the Python model's
output for the same inputs.
"""
import argparse
import importlib.util
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("rvf", ROOT / "experiments" / "regime_vs_fixed.py")
rvf = importlib.util.module_from_spec(spec)
spec.loader.exec_module(rvf)

def gate_lines(n1, n2, n3):
    return [
        f"BOOL.{n1} r6,r1,r3",
        f"BOOL.{n2} r7,r4,r5",
        f"BOOL.{n3} r8,r6,r7",
    ]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="build/lut_regime.nas")
    ap.add_argument("--expected", default="build/lut_regime.expected")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--routed", action="store_true")
    args = ap.parse_args()

    X = np.arange(256, dtype=np.uint32)
    Y = rvf.task_teacher_piecewise(X, args.seed).astype(np.uint8)
    router_bit = 0
    if args.routed:
        # fit one tree per route, router x0 (the teacher's selector)
        ns = rvf.fit_routed(X, Y, router_bit)
        pred = rvf.pred_routed(ns, X, router_bit)
    else:
        _, n = rvf.fit_fixed(X, Y)
        ns = [n]
        pred = rvf.tree(*n, X)

    lines = []
    lines.append("; learned LUT regime tree, generated by experiments/export_lut.py")
    lines.append(".org 0")
    lines.append("main:")
    lines.append("MOVI r13,1")
    lines.append("MOVI r10,0")
    lines.append("loop:")
    lines.append("MOVI r11,256")
    lines.append("CMP r10,r11")
    lines.append("JMP[GE] @done")
    lines.append("MOVI r2,1")
    lines.append("BOOL.8 r1,r10,r2")
    lines.append("SHR r3,r10,1")
    lines.append("BOOL.8 r3,r3,r2")
    lines.append("SHR r4,r10,2")
    lines.append("BOOL.8 r4,r4,r2")
    lines.append("SHR r5,r10,3")
    lines.append("BOOL.8 r5,r5,r2")
    if args.routed:
        lines.append("CMP r1,r0")
        lines.append("JMP[EQ] @route0")
        lines.extend(gate_lines(*ns[1]))
        lines.append("JMP @after")
        lines.append("route0:")
        lines.extend(gate_lines(*ns[0]))
        lines.append("after:")
    else:
        lines.extend(gate_lines(*ns[0]))
    lines.append("BOOL.8 r8,r8,r2")
    lines.append("MOVI r9,48")
    lines.append("ADD r8,r8,r9")
    lines.append("PUTC r8")
    lines.append("MOVI r8,10")
    lines.append("PUTC r8")
    lines.append("ADD r10,r10,r13")
    lines.append("JMP @loop")
    lines.append("done:")
    lines.append("HALT")

    Path(args.out).write_text("\n".join(lines) + "\n")
    Path(args.expected).write_text("".join(f"{int(v)}\n" for v in pred))
    print(f"wrote {args.out} and {args.expected} ({'routed' if args.routed else 'fixed'}, seed={args.seed})")
    if args.routed:
        print("router bit", router_bit, "trees", ns)

if __name__ == "__main__":
    main()
